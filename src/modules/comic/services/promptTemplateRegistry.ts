/**
 * **画面描述环节（panel-prompt / panel-prompt-chapter）的变量边界**：
 * 只给「分镜内容 + 资产视觉设定 + 资产参考图号清单」，**不给共用属性正文** ——
 * 共用属性（插入最前 / 插入最后）由 `composeFinalPrompt` 在生图时拼接到描述之外，
 * 既不进推导提示词、也不进 `imagePrompt` 字段。好处：模型只负责画面本身与图号引用，
 * 改画风 / 换共用属性图不必重跑模型，固定文案也不会被模型改写、漏句或串图。
 * 图号不受影响：清单里的图号沿用生图时的真实顺序（共用属性图占号但不出现在清单里）。
 */

/**
 * 模板变量定义：变量是否进入提示词完全由模板作者决定，不做任何自动追加。
 * 模板里没写 {{变量名}}，该变量就不会出现在最终提示词里。
 */
