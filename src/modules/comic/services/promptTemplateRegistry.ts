/**
 * **画面描述环节（panel-prompt / panel-prompt-chapter）的变量边界**：
 * 只给分镜内容与上下文，不给共用属性、资产参考图清单或图号。
 * `composeFinalPrompt` 会在生图时按当前图片顺序动态拼接这些内容，因此改共用属性、
 * 换视觉状态或参考图都不需要重跑画面内容推导。
 */

/**
 * 模板变量定义：变量是否进入提示词完全由模板作者决定，不做任何自动追加。
 * 模板里没写 {{变量名}}，该变量就不会出现在最终提示词里。
 */
export interface PromptVariableSpec {
  /** 变量名（中文），模板中写作 {{变量名}} */
  name: string
  /** 说明：设置页变量 tag 的 tooltip */
  desc: string
  /** 旧英文别名：兼容存量模板，渲染与迁移时归一化为中文名 */
  legacy?: string[]
  /** 变量已插入模板但值为空时的替换文案（仅模板内占位，不是自动追加） */
  emptyText?: string
}

